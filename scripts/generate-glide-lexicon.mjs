import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { words } from 'popular-english-words';

// Keep the runtime dictionary small and deterministic. The source list is
// frequency-ranked and ISC-licensed (popular-english-words, Tim Koop).
const storyWords = [
  'examine', 'inventory', 'look', 'take', 'drop', 'open', 'close', 'unlock',
  'lock', 'use', 'enter', 'exit', 'north', 'south', 'east', 'west', 'upstairs',
  'downstairs', 'up', 'down', 'in', 'out', 'talk', 'ask', 'tell', 'wait', 'again',
  'search', 'read', 'push', 'pull', 'move', 'turn', 'switch', 'climb', 'jump',
  'listen', 'smell', 'touch', 'attack', 'give', 'throw', 'wear', 'remove', 'put',
  'get', 'go', 'save', 'restore', 'quit', 'map', 'help', 'yes', 'no', 'room',
  'door', 'key', 'phone', 'wallet', 'bedroom', 'bathroom', 'kitchen', 'table',
  'lamp', 'box', 'chest', 'letter', 'note', 'paper', 'book', 'window', 'drawer',
];
const artifacts = new Set(['nbsp', 'www', 'com', 'href', 'wikipedia', 'redirect']);
const lexicon = [...new Set([
  ...storyWords,
  ...words.getMostPopular(20000).filter(word => /^[a-z]{2,14}$/.test(word) && !artifacts.has(word)),
])];

const output = `// Generated by scripts/generate-glide-lexicon.mjs from popular-english-words (ISC).\n` +
  `export const GLIDE_WORDS = ${JSON.stringify(lexicon.join(' '))}.split(' ');\n`;
writeFileSync(fileURLToPath(new URL('../services/glide-lexicon.ts', import.meta.url)), output);
console.log(`Generated ${lexicon.length} offline glide words.`);
